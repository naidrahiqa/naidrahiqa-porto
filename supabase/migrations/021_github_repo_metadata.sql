  add column if not exists repo_name text,
  add column if not exists repo_stars int not null default 0,
  add column if not exists repo_forks int not null default 0,
  add column if not exists repo_is_fork boolean not null default false,
  add column if not exists repo_archived boolean not null default false,
  add column if not exists repo_pushed_at timestamptz,
  add column if not exists repo_homepage text,
  add column if not exists repo_topics text[] not null default '{}';

create index if not exists projects_repo_name_idx
  on public.projects (repo_name);

